import AppKit
import Foundation
import Observation

/// Where the app keeps the emulated machine, and how it finds the bundled simulator.
enum MachinePaths {
    static let support: URL = {
        let base = FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0]
        return base.appendingPathComponent("ATT3B2", isDirectory: true)
    }()
    static var machine: URL { support.appendingPathComponent("700", isDirectory: true) }
    static var snapshots: URL { machine.appendingPathComponent("snapshots", isDirectory: true) }
    static var disk: URL { machine.appendingPathComponent("disk0.img") }
    static var runIni: URL { machine.appendingPathComponent("run.ini") }

    /// Contents/Resources inside the .app; falls back to the repo layout when run via `swift run`.
    static var resources: URL {
        if let r = Bundle.main.resourceURL, FileManager.default.fileExists(atPath: r.appendingPathComponent("sim").path) {
            return r
        }
        return URL(fileURLWithPath: #filePath)            // app/Sources/ATT3B2/Machine.swift
            .deletingLastPathComponent().deletingLastPathComponent().deletingLastPathComponent()
            .appendingPathComponent("build/resources", isDirectory: true)
    }
    static var simulator: URL { resources.appendingPathComponent("sim/3b2-700") }
    static var seed: URL { resources.appendingPathComponent("seed", isDirectory: true) }
}

enum PowerState: String {
    case off = "Off"
    case selfTest = "Self-test"
    case booting = "Booting UNIX"
    case running = "Running"
    case shuttingDown = "Shutting down"
    case halted = "Halted (sim>)"

    var isOn: Bool { self != .off }
}

struct Snapshot: Identifiable, Hashable {
    let url: URL
    let date: Date
    var id: URL { url }
    var name: String { url.deletingPathExtension().lastPathComponent }
}

/// The 3B2/700: owns the simulator configuration, power state and snapshots.
/// The simulator process itself lives in `ConsoleTerminalView`, which reports what it
/// sees on the console back here.
@MainActor
@Observable
final class Machine {
    static let shared = Machine()

    var state: PowerState = .off
    var lastError: String?
    var snapshots: [Snapshot] = []
    var poweredOnAt: Date?

    /// Set by the console view; used to send keystrokes and SIMH commands.
    weak var console: ConsoleTerminalView?

    private var pendingSimCommands: [String] = []
    private var awaitingSimPrompt = false
    private var recent = ""            // rolling tail of console output, for state detection
    private var poweredOff = false

    // MARK: - Setup

    /// First launch: clone the bundled ROM/NVRAM/clock files and golden disk into
    /// Application Support. APFS clones make the 600 MB disk copy instant.
    func prepare() {
        let fm = FileManager.default
        do {
            try fm.createDirectory(at: MachinePaths.snapshots, withIntermediateDirectories: true)
            for name in ["3b2_700.bin", "nvram.bin", "tod.bin"] {
                let dst = MachinePaths.machine.appendingPathComponent(name)
                if !fm.fileExists(atPath: dst.path) {
                    try fm.copyItem(at: MachinePaths.seed.appendingPathComponent(name), to: dst)
                }
            }
            if !fm.fileExists(atPath: MachinePaths.disk.path) {
                try clone(MachinePaths.seed.appendingPathComponent("golden.img"), to: MachinePaths.disk)
            }
            refreshSnapshots()
        } catch {
            lastError = "Could not set up the machine in \(MachinePaths.machine.path): \(error.localizedDescription)"
        }
    }

    private func clone(_ src: URL, to dst: URL) throws {
        // copyItem uses clonefile(2) on APFS, falling back to a real copy elsewhere.
        try FileManager.default.copyItem(at: src, to: dst)
    }

    private func writeRunIni() throws {
        let ini = """
        ; Generated by ATT3B2.app on each power-on.
        load -r 3b2_700.bin
        set cpu 64M
        set cpu idle
        attach nvram nvram.bin
        attach tod tod.bin
        set scsi1 enable
        set scsi1 sd630
        attach scsi1 disk0.img
        set ports enable
        set ports lines=8
        attach ports 127.0.0.1:9001;notelnet
        set ni enable
        attach ni nat:tcp=2323:10.0.2.15:23,tcp=2121:10.0.2.15:21
        boot

        """
        try ini.write(to: MachinePaths.runIni, atomically: true, encoding: .utf8)
    }

    // MARK: - Power

    func powerOn() {
        guard !state.isOn, let console else { return }
        lastError = nil
        guard FileManager.default.isExecutableFile(atPath: MachinePaths.simulator.path) else {
            lastError = "Simulator not found at \(MachinePaths.simulator.path). Rebuild the app with scripts/build-app.sh."
            return
        }
        do { try writeRunIni() } catch {
            lastError = "Could not write run.ini: \(error.localizedDescription)"
            return
        }
        recent = ""
        poweredOff = false
        pendingSimCommands = []
        awaitingSimPrompt = false
        state = .selfTest
        poweredOnAt = Date()
        console.startSimulator(executable: MachinePaths.simulator.path,
                               args: ["-q", MachinePaths.runIni.lastPathComponent],
                               directory: MachinePaths.machine.path)
    }

    /// The front-panel switch: UNIX syncs and powers off (patch 0003).
    func pressPowerSwitch() {
        guard state.isOn else { powerOn(); return }
        state = .shuttingDown
        simCommand("set csr powerdown")
    }

    /// Pull the plug. Unsynced data may be lost, exactly like the real thing.
    func forceOff() {
        console?.terminateSimulator()
    }

    func reset() {
        guard state.isOn else { return }
        state = .selfTest
        simCommand("reset all", resume: false)
        simCommand("boot")
    }

    /// Run a SIMH command: Ctrl-E stops the CPU and gives a `sim>` prompt, the command
    /// runs there, then `continue` resumes (unless `resume` is false).
    func simCommand(_ command: String, resume: Bool = true) {
        pendingSimCommands.append(command)
        if resume, command != "boot" { pendingSimCommands.append("continue") }
        if !awaitingSimPrompt {
            awaitingSimPrompt = true
            console?.sendBytes([0x05])
        }
    }

    // MARK: - Console observation (called by ConsoleTerminalView)

    func consoleOutput(_ bytes: ArraySlice<UInt8>) {
        let text = String(decoding: bytes, as: UTF8.self)
        recent = String((recent + text).suffix(2048))

        if recent.contains("System Powered Off") {
            // UNIX powered the machine off; the simulator now sits at sim>. Quit it so
            // the TOD clock and NVRAM are written back to their files.
            poweredOff = true
            state = .shuttingDown
        }
        if recent.hasSuffix("sim> ") {
            recent = ""
            if poweredOff {
                console?.sendBytes(Array("quit\r".utf8))
                return
            }
            if let next = pendingSimCommands.first {
                pendingSimCommands.removeFirst()
                console?.sendBytes(Array((next + "\r").utf8))
                if pendingSimCommands.isEmpty { awaitingSimPrompt = false }
                return
            }
            awaitingSimPrompt = false
            if state != .shuttingDown { state = .halted }
            return
        }
        if recent.contains("SELF-CHECK") || recent.contains("FW ERROR") { advance(to: .selfTest) }
        if recent.contains("The system is coming up") { advance(to: .booting) }
        if recent.contains("Console Login:") { advance(to: .running); recent = "" }
        if recent.contains("The system is coming down") { advance(to: .shuttingDown) }
    }

    private func advance(to new: PowerState) {
        if state != new && state != .off { state = new }
    }

    func simulatorExited(code: Int32?) {
        state = .off
        poweredOnAt = nil
        awaitingSimPrompt = false
        pendingSimCommands = []
        if let code, code != 0 { lastError = "Simulator exited with status \(code)." }
        refreshSnapshots()
    }

    // MARK: - Snapshots (only while powered off, so the disk image is consistent)

    func refreshSnapshots() {
        let fm = FileManager.default
        let urls = (try? fm.contentsOfDirectory(at: MachinePaths.snapshots, includingPropertiesForKeys: [.creationDateKey])) ?? []
        snapshots = urls.filter { $0.pathExtension == "img" }.map { url in
            let date = (try? url.resourceValues(forKeys: [.creationDateKey]).creationDate) ?? .distantPast
            return Snapshot(url: url, date: date)
        }.sorted { $0.date > $1.date }
    }

    func takeSnapshot(named label: String) {
        guard !state.isOn else { lastError = "Power off the machine before taking a snapshot."; return }
        let f = DateFormatter(); f.dateFormat = "yyyyMMdd-HHmmss"
        let safe = label.replacingOccurrences(of: "[^A-Za-z0-9_-]+", with: "-", options: .regularExpression)
        let dst = MachinePaths.snapshots.appendingPathComponent("\(f.string(from: Date()))-\(safe.isEmpty ? "snapshot" : safe).img")
        do { try clone(MachinePaths.disk, to: dst) } catch { lastError = error.localizedDescription }
        refreshSnapshots()
    }

    func restore(_ snap: Snapshot) {
        guard !state.isOn else { lastError = "Power off the machine before restoring."; return }
        restoreDisk(from: snap.url)
    }

    func restoreFactory() {
        guard !state.isOn else { lastError = "Power off the machine before restoring."; return }
        restoreDisk(from: MachinePaths.seed.appendingPathComponent("golden.img"))
    }

    private func restoreDisk(from src: URL) {
        let fm = FileManager.default
        let tmp = MachinePaths.machine.appendingPathComponent("disk0.restoring.img")
        do {
            try? fm.removeItem(at: tmp)
            try clone(src, to: tmp)
            _ = try fm.replaceItemAt(MachinePaths.disk, withItemAt: tmp)
        } catch {
            lastError = "Restore failed: \(error.localizedDescription)"
        }
    }

    func deleteSnapshot(_ snap: Snapshot) {
        try? FileManager.default.removeItem(at: snap.url)
        refreshSnapshots()
    }
}
