#!/bin/sh
# Build the AT&T 630 MTG host software for macOS into a $DMD tree:
#   - dmd-layers: Dave Dykstra's pseudo-tty layers (the 630's windowing host)
#   - freesdp630: the 630 software development package's host tools (dmdld, ...)
#   - mtg-binaries: prebuilt downloadable 630 programs (.m)
#   - host630/: our 3b2line window connector, a movelogin stub and the startup file
# Usage: scripts/build-630host.sh [OUT]   (default build/630host)
set -e
ROOT=$(cd "$(dirname "$0")/.." && pwd)
OUT=${1:-$ROOT/build/630host}
V=$ROOT/vendor
COMPAT=$ROOT/host630/compat/macos

for r in dmd-layers freesdp630 mtg-binaries; do
  [ -d "$V/$r" ] || { echo "missing vendor/$r — run scripts/fetch-assets.sh" >&2; exit 1; }
done

# 1990s K&R C: quiet the modern diagnostics, keep the ones that matter on LP64.
CFLAGS="-O -w -Dconst= -std=gnu89 -I$COMPAT -Wno-implicit-function-declaration -Wno-int-conversion \
-Wno-incompatible-pointer-types -Wno-return-type -Wno-implicit-int"

rm -rf "$OUT"
mkdir -p "$OUT"

# Pseudo-tty layers. $DMD/xt must be writable at run time; the app points DMD at a
# directory in Application Support whose bin/lib/include link back here.
( cd "$V/dmd-layers" && make clean >/dev/null 2>&1 || true
  make DMD="$OUT" EXTRACFLAGS="$CFLAGS" >/dev/null
  make DMD="$OUT" EXTRACFLAGS="$CFLAGS" install >/dev/null 2>&1 || true
  make clean >/dev/null 2>&1 || true )
[ -x "$OUT/bin/layers" ] || { echo "layers did not build" >&2; exit 1; }
rm -rf "$OUT/xt"

# SDP host tools. Terminal-side parts need the 68000 cross compiler (not built);
# their prebuilt .m files come from mtg-binaries instead.
mkdir -p "$OUT/include/ccs" "$OUT/lib/demolib" "$OUT/lib/demobin" "$OUT/lib/630bin"
cp "$V"/freesdp630/ccs/inc/common/*.h "$V"/freesdp630/ccs/inc/mc68/*.h "$OUT/include/ccs/"
( cd "$V/freesdp630/include" && make DMD="$OUT" install >/dev/null 2>&1 || true )
touch "$V/freesdp630/dmdld/shakecode.c"       # generated by the cross assembler; checked in
for d in dmdld dmdversion dmdcat jx wtinit loadfont; do
  ( cd "$V/freesdp630/$d" && make DMD="$OUT" DMDSYS="$OUT" EXTRACFLAGS="$CFLAGS" install >/dev/null 2>&1 || true
    make DMD="$OUT" clean >/dev/null 2>&1 || true )
done
for t in dmdld dmdversion dmdcat jx wtinit; do
  [ -x "$OUT/bin/$t" ] || { echo "$t did not build" >&2; exit 1; }
done
# Host-side wrapper scripts for programs whose .m we take prebuilt.
for s in ucache/ucache icon/icon demo/dmddemo; do
  sed -e "s+DeFdMd+$OUT+g" "$V/freesdp630/$s.sh" > "$OUT/bin/$(basename $s)"
  chmod 755 "$OUT/bin/$(basename $s)"
done

B=$V/mtg-binaries
cp "$B"/sdp630/*.m "$OUT/lib/"
cp "$B"/sdp630/demolib/* "$OUT/lib/demolib/"
for d in games misc tc630 exp630; do cp "$B/$d"/*.m "$OUT/lib/630bin/"; done

# Our pieces.
cc -O2 -Wall -o "$OUT/bin/3b2line" "$ROOT/host630/3b2line.c"
cp "$ROOT/host630/movelogin" "$OUT/lib/layersys/movelogin"
chmod 755 "$OUT/lib/layersys/movelogin"
cp "$ROOT/host630/layersrc" "$ROOT/host630/toolsh" "$OUT/lib/"
chmod 755 "$OUT/lib/toolsh"
rm -rf "$OUT/man"
echo "built $OUT"
